#!/usr/bin/env bash

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
NODES_ROOT="${ORTHUS_NODES_ROOT:-${HOME}/.orthus/nodes}"

die() {
  echo "error: $*" >&2
  exit 1
}

require_node() {
  local node="${1:-}"
  if [[ -z "${node}" ]]; then
    die "NODE required"
  fi
  printf '%s' "${node}"
}

node_env_profile() {
  printf '%s' "${ORTHUS_NODE_ENV:-${ORTHUS_NODE_PROFILE:-}}"
}

source_node_profile_env() {
  local node="$1"
  local stem="$2"
  local profile
  profile="$(node_env_profile)"
  if [[ -z "${profile}" || "${profile}" == "base" ]]; then
    return
  fi
  if [[ ! "${profile}" =~ ^[A-Za-z0-9_-]+$ ]]; then
    die "ORTHUS_NODE_ENV must be alphanumeric, dash, or underscore"
  fi
  local override_env="${NODES_ROOT}/${node}/${stem}.${profile}.env"
  if [[ ! -f "${override_env}" ]]; then
    die "ORTHUS_NODE_ENV=${profile} but ${override_env} is missing"
  fi
  # shellcheck disable=SC1090
  set -a
  source "${override_env}"
  set +a
}

sanitize_db_suffix() {
  local node="$1"
  local suffix
  suffix="$(printf '%s' "${node}" | tr '[:upper:]-' '[:lower:]_' | tr -cd 'a-z0-9_')"
  if [[ -z "${suffix}" ]]; then
    die "cannot derive DB suffix from node '${node}'"
  fi
  printf '%s' "${suffix}"
}

node_kind_for() {
  local node="$1"
  local override="${ORTHUS_NODE_KIND_OVERRIDE:-${NODE_KIND:-}}"
  if [[ -n "${override}" ]]; then
    if [[ "${override}" != "company" && "${override}" != "personal" ]]; then
      die "NODE_KIND must be company or personal"
    fi
    printf '%s' "${override}"
    return
  fi
  if [[ "${node}" == "company" ]]; then
    printf 'company'
  elif [[ "${node}" == company-* ]]; then
    printf 'company'
  else
    printf 'personal'
  fi
}

default_api_port_for() {
  local node="$1"
  local override="${ORTHUS_NODE_API_PORT:-${API_PORT:-}}"
  if [[ -n "${override}" ]]; then
    printf '%s' "${override}"
    return
  fi
  if [[ "${node}" == "company-staging" ]]; then
    printf '8920'
    return
  fi
  if [[ "${node}" == "personal-a-staging" ]]; then
    printf '8930'
    return
  fi
  if [[ "${node}" == "company" ]]; then
    printf '8820'
  else
    printf '8830'
  fi
}

default_web_port_for() {
  local node="$1"
  local override="${ORTHUS_NODE_WEB_PORT:-${WEB_PORT:-}}"
  if [[ -n "${override}" ]]; then
    printf '%s' "${override}"
    return
  fi
  if [[ "${node}" == "company-staging" ]]; then
    printf '3920'
    return
  fi
  if [[ "${node}" == "personal-a-staging" ]]; then
    printf '3930'
    return
  fi
  if [[ "${node}" == "company" ]]; then
    printf '3820'
  else
    printf '3830'
  fi
}

