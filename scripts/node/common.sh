load_node_env() {
  local node="$1"
  local node_env="${NODES_ROOT}/${node}/node.env"

  if [[ ! -f "${node_env}" ]]; then
    die "${node_env} missing; run make node-bootstrap NODE=${node}"
  fi

  # shellcheck disable=SC1090
  set -a
  source "${node_env}"
  set +a
  source_node_profile_env "${node}" "node"

  if [[ "${ORTHUS_NODE_ID:-}" != "${node}" ]]; then
    die "ORTHUS_NODE_ID=${ORTHUS_NODE_ID:-} does not match NODE=${node}"
  fi
  if [[ "${ORTHUS_NODE_KIND:-}" != "company" && "${ORTHUS_NODE_KIND:-}" != "personal" ]]; then
    die "ORTHUS_NODE_KIND must be company or personal"
  fi
  if [[ -z "${ORTHUS_NODE_DB:-}" ]]; then
    die "ORTHUS_NODE_DB missing in ${node_env}"
  fi
  if [[ -z "${ORTHUS_WIKI_STORE:-}" ]]; then
    die "ORTHUS_WIKI_STORE missing in ${node_env}"
  fi

  mkdir -p "${ORTHUS_WIKI_STORE}" "${ORTHUS_NODE_ROOT:-${NODES_ROOT}/${node}}/logs"
}

load_web_env() {
  local node="$1"
  local web_env="${NODES_ROOT}/${node}/web.env"
  if [[ -f "${web_env}" ]]; then
    # shellcheck disable=SC1090
    set -a
    source "${web_env}"
    set +a
  fi
  source_node_profile_env "${node}" "web"
  export NEXT_PUBLIC_API_BASE="${NEXT_PUBLIC_API_BASE:-${ORTHUS_WEB_API_BASE:-http://localhost:${ORTHUS_API_PORT:-8820}}}"
}

assert_not_repo_wiki_store() {
  local resolved
  resolved="$(python3 - <<'PY'
import os
from pathlib import Path
print(Path(os.environ["ORTHUS_WIKI_STORE"]).expanduser().resolve())
PY
)"
  if [[ "${resolved}" == "${REPO_ROOT}/wiki-store" ]]; then
    die "ORTHUS_WIKI_STORE points at repo wiki-store; node store must be external"
  fi
}
